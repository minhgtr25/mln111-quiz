create table if not exists public.user_progress (
    user_id uuid primary key references auth.users (id) on delete cascade,
    payload jsonb not null default '{"version":1,"starred":{},"wrong":{},"answered":{},"correct":{}}'::jsonb,
    updated_at timestamptz not null default now()
);

alter table public.user_progress enable row level security;

drop policy if exists "Users can read their own progress" on public.user_progress;
create policy "Users can read their own progress"
    on public.user_progress for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert their own progress" on public.user_progress;
create policy "Users can insert their own progress"
    on public.user_progress for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own progress" on public.user_progress;
create policy "Users can update their own progress"
    on public.user_progress for update to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

grant select, insert, update on public.user_progress to authenticated;

do $$
begin
    if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
       and not exists (
           select 1 from pg_publication_tables
           where pubname = 'supabase_realtime'
             and schemaname = 'public'
             and tablename = 'user_progress'
       ) then
        alter publication supabase_realtime add table public.user_progress;
    end if;
end
$$;


create table if not exists public.questions (
    id integer generated by default as identity primary key,
    question text not null,
    correct_option text not null check (correct_option in ('A', 'B', 'C', 'D', 'E', 'F'))
);

create table if not exists public.question_options (
    question_id integer not null references public.questions(id) on delete cascade,
    option_key text not null check (option_key in ('A', 'B', 'C', 'D', 'E', 'F')),
    option_text text not null,
    option_order smallint not null,
    primary key (question_id, option_key),
    unique (question_id, option_order)
);

create table if not exists public.learning_rules (
    id text primary key,
    title text not null,
    tag text not null,
    icon text not null,
    formula text not null
);

create table if not exists public.rule_questions (
    rule_id text not null references public.learning_rules(id) on delete cascade,
    question_id integer not null references public.questions(id) on delete cascade,
    primary key (rule_id, question_id)
);

alter table public.questions enable row level security;
alter table public.question_options enable row level security;
alter table public.learning_rules enable row level security;
alter table public.rule_questions enable row level security;

drop policy if exists "Public can read questions" on public.questions;
create policy "Public can read questions" on public.questions for select to anon, authenticated using (true);
drop policy if exists "Public can read question options" on public.question_options;
create policy "Public can read question options" on public.question_options for select to anon, authenticated using (true);
drop policy if exists "Public can read learning rules" on public.learning_rules;
create policy "Public can read learning rules" on public.learning_rules for select to anon, authenticated using (true);
drop policy if exists "Public can read rule question links" on public.rule_questions;
create policy "Public can read rule question links" on public.rule_questions for select to anon, authenticated using (true);

grant select on public.questions, public.question_options, public.learning_rules, public.rule_questions to anon, authenticated;
